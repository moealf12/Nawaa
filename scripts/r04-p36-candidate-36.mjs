// R04-P3.6: observe the actual PR code in a disposable local Node server.
// Unlike the frozen production audit, these requests hit the candidate,
// not Render's previously deployed main. No source retries, DB, Meili or writes.
// This is acquisition evidence, never human ranking/merchant certification.
import {spawn,execFileSync} from "node:child_process";
import {once} from "node:events";
import {readFileSync,writeFileSync} from "node:fs";
import net from "node:net";
import {groupComparableOffers} from "../src/search-core.mjs";
import {buildSearchPresentationSections} from "../src/search-result-presentation.mjs";
import {aggregateSourceErrorEvidence,mergeSourceErrorEvidence}
  from "./r04-source-failure-forensics.mjs";
import {correlateLiveSearchTraces} from "./r04-p46-correlate-live-traces.mjs";
import {createBoundedLogFrameParser} from "./r04-p49-log-frames.mjs";
import {summarizeGroupClassificationEvidence} from "./r04-p47-classification-evidence.mjs";

const TRACE_ENABLED=process.env.NAWAA_P46_TRACE_ENABLED==="1";
const SHA=execFileSync("git",["rev-parse","HEAD"],{encoding:"utf8"}).trim();
if(!/^[0-9a-f]{40}$/.test(SHA))throw Error("INVALID_CANDIDATE_SHA");
const corpus=JSON.parse(readFileSync(new URL("../engineering/execution/search-truth-corpus.json",import.meta.url),"utf8"));
if(!Array.isArray(corpus.queryCases)||corpus.queryCases.length!==36 ||
  new Set(corpus.queryCases.map(x=>x.id)).size!==36)throw Error("INVALID_FROZEN_CORPUS");
const PORT=await new Promise((resolve,reject)=>{
  const server=net.createServer();
  server.once("error",reject);
  server.listen(0,"127.0.0.1",()=>{
    const p=server.address().port;
    server.close(()=>resolve(p));
  });
});
const base="http://127.0.0.1:"+PORT;
const child=spawn(process.execPath,["server/server.mjs"],{
  env:{...process.env,PORT:String(PORT),NODE_ENV:"production",
    NAWAA_CANONICAL_INDEX_TEST:"0",NAWAA_OMEGA_INDEX_ONLY:"0",
    DATABASE_URL:"",MEILI_HOST:"",MEILI_MASTER_KEY:"",
    NOON_ENABLED:"false",EBAY_ENABLED:"false",CARREFOUR_ENABLED:"false",
    NAWAA_SEARCH_DIAGNOSTIC_TRACE:TRACE_ENABLED?"1":"0"},
  stdio:["ignore","pipe","pipe"],
});
// The candidate was previously discarding the only per-stage evidence of
// 12-second Q08 tails. Preserve *only* low-cardinality, sanitized, aggregate
// slow-pipeline events already emitted by server.mjs; never source URLs,
// titles, query strings, prices, response bodies or arbitrary log lines.
// Requests run with concurrency=2, so these events are deliberately NOT
// attributed to a particular query without a proven request correlation ID.
let slowPipelineEvents=0;
const criticalPathEvents=[],httpTraceEvents=[];
let traceDropped=0;
const safeNumber=v=>Number.isFinite(v)?Math.max(0,Math.round(v)):null;
const frameParser=createBoundedLogFrameParser(line=>{
    // Traces are generated by the disposable candidate itself; gather only
    // bounded JSON records with exact short IDs. Do not forward raw source logs.
    if(TRACE_ENABLED){
      for(const [marker,target] of [
        ["NAWAA_SEARCH_CRITICAL_PATH ",criticalPathEvents],
        ["NAWAA_SEARCH_HTTP_LIFECYCLE ",httpTraceEvents],
      ]){
        const pos=line.indexOf(marker);
        if(pos<0)continue;
        if(target.length>=96){traceDropped++;continue;}
        try{
          const raw=JSON.parse(line.slice(pos+marker.length));
          const traceId=marker.includes("CRITICAL_PATH")?raw?.generationId:raw?.requestId;
          if(/^[a-f0-9]{16}$/.test(traceId||""))target.push(raw);
        }catch{traceDropped++;}
      }
    }
    const marker="NAWAA_SEARCH_JSON_PIPELINE ";
    const idx=line.indexOf(marker);
    if(idx<0||slowPipelineEvents>=36)continue;
    try{
      const raw=JSON.parse(line.slice(idx+marker.length));
      const onlyKnownSources=(Array.isArray(raw.providerTimings)?raw.providerTimings:[])
        .slice(0,24).map(v=>({
          sourceId:/^[a-z0-9:_-]{2,56}$/i.test(v?.sourceId)?v.sourceId:"unknown",
          pass:v?.pass==="fallback"?"fallback":"primary",
          providerWallMs:safeNumber(v?.providerWallMs),
          queueMs:safeNumber(v?.queueMs),
          offers:safeNumber(v?.offers),
        }));
      const barriers=(Array.isArray(raw.primaryComponents)?raw.primaryComponents:[])
        .slice(0,6).map(v=>({
          component:["amazon-sa","provider-pass","meilisearch","persisted"].includes(v?.component)
            ?v.component:"unknown",
          settledAtMs:safeNumber(v?.settledAtMs),
          failed:v?.failed===true,
        }));
      slowPipelineEvents++;
      console.log("R04_P36_UNATTRIBUTED_SLOW_PIPELINE "+JSON.stringify({
        unattributedConcurrentRequests:true,
        primaryAcquiredMs:safeNumber(raw.primaryAcquiredMs),
        preSelectionMs:safeNumber(raw.preSelectionMs),
        finalizationMs:safeNumber(raw.finalizationMs),
        totalMs:safeNumber(raw.totalMs),
        deadlineExceeded:raw.deadlineExceeded===true,
        fallbackUsed:raw.fallbackUsed===true,
        hardDeniedFallbackStores:safeNumber(raw.hardDeniedFallbackStores),
        providerTimings:onlyKnownSources,
        primaryComponents:barriers,
      }));
    }catch{}
},{onDrop:()=>{traceDropped++;}});
child.stdout.on("data",chunk=>frameParser.push(chunk));
child.stderr.on("data",()=>{});
const startedAt=new Date().toISOString(), rows=Array(36).fill(null);
const knownFailureNames=new Set(["TimeoutError","AbortError","SyntaxError","TypeError"]);
let fatal=null;

async function ready(){
  for(let i=0;i<60;i++){
    if(child.exitCode!==null)throw Error("CANDIDATE_SERVER_EXITED");
    try{
      const res=await fetch(base+"/health",{signal:AbortSignal.timeout(1000)});
      const health=await res.json();
      if(res.status===200&&health?.ok===true)return;
    }catch{}
    await new Promise(r=>setTimeout(r,100));
  }
  throw Error("CANDIDATE_HEALTH_UNAVAILABLE");
}
async function probe(q){
  const started=Date.now();
  let phase="headers";
  try {
    const res=await fetch(base+"/api/search?q="+encodeURIComponent(q.query),{
      headers:{accept:"application/json","cache-control":"no-cache"},
      signal:AbortSignal.timeout(32000),redirect:"error",
    });
    const requestTraceId=TRACE_ENABLED?res.headers.get("x-nawaa-request-id"):null;
    phase="body";
    if(Number(res.headers.get("content-length")||0)>3_000_000)throw Error("RESPONSE_OVERSIZED");
    const bytes=await res.arrayBuffer();
    if(bytes.byteLength>3_000_000)throw Error("RESPONSE_OVERSIZED");
    phase="parse";
    const body=JSON.parse(new TextDecoder().decode(bytes));
    if(res.status!==200||!Array.isArray(body?.offers)||
      typeof body?.coverage?.partial!=="boolean")throw Error("INVALID_RESPONSE_CONTRACT");
    phase="validate";
    const valid=body.offers.every(o=>{
      if(typeof o?.title!=="string"||!o.title.trim()||
         !Number.isFinite(o.productPrice)||o.productPrice<=0||
         o.currency!=="SAR"||!o.merchant)return false;
      try {const url=new URL(o.sourceUrl);return url.protocol==="https:";}catch{return false;}
    });
    if(!valid)throw Error("INVALID_OFFER_CONTRACT");
    // Production-like live mode has neither a fixture index nor a persisted
    // catalog. Every candidate offer must come from an actual live connector.
    if(body.offers.some(o=>o.dataKind!=="live"))throw Error("NON_LIVE_OFFER_IN_ACCEPTANCE");
    const grouped=groupComparableOffers(body.offers,"lowest");
    const sections=buildSearchPresentationSections(q.query,grouped);
    if(sections.partitionedGroups!==grouped.length)throw Error("PRESENTATION_PARTITION_LOSS");
    const classifierEvidence=summarizeGroupClassificationEvidence(q.query,grouped);
    if(classifierEvidence.invalidDecisions>0||
       classifierEvidence.omittedGroups===0 &&
       (classifierEvidence.laneCounts.direct||0)!==sections.classified.primaryGroups.length)
      throw Error("CLASSIFIER_AUDIT_PARITY_LOSS");
    const failures=aggregateSourceErrorEvidence(body.errors);
    const row={
      id:q.id,group:q.group,language:q.language,status:"OBSERVED",
      requestTraceId:/^[a-f0-9]{16}$/.test(requestTraceId||"")?requestTraceId:null,
      elapsedMs:Date.now()-started,
      serverDurationMs:Number.isFinite(body.durationMs)?Math.round(body.durationMs):null,
      offers:body.offers.length,groups:grouped.length,
      primaryGroups:sections.exactGroups.length,relatedGroups:sections.relatedGroups.length,
      // These are the customer presentation lanes from the same production
      // partition function. Counts, not titles, prices or query-specific fixes.
      classifierEvidence,
      presentationLanes:Object.fromEntries(sections.secondarySections
        .filter(section=>["alternative","accessory","bundle","other"].includes(section.key))
        .map(section=>[section.key,section.groups.length])),
      partial:body.coverage.partial,
      deadlineExceeded:body.coverage.deadlineExceeded===true,
      providersPending:body.coverage.providersPending??null,
      sourceErrors:failures.reported,sourceErrorBreakdown:failures,
      localCooldownSkips:failures.buckets.reduce((n,b)=>n+
        (b.failureClass==="SOURCE_ACCESS_DENIED_COOLDOWN"||
         b.failureClass==="SOURCE_RATE_LIMIT_COOLDOWN"?b.count:0),0),
      observedUpstreamDenials:failures.buckets.reduce((n,b)=>n+
        (b.failureClass==="HTTP_403_ACCESS_DENIED"||
         b.failureClass==="HTTP_429_RATE_LIMITED"?b.count:0),0),
    };
    console.log("R04_P36_CANDIDATE_QUERY "+JSON.stringify({
      id:row.id,status:row.status,elapsedMs:row.elapsedMs,
      offers:row.offers,primaryGroups:row.primaryGroups,
      presentationLanes:row.presentationLanes,
      classifierReasons:row.classifierEvidence.reasonCounts,
      classifierCoverage:row.classifierEvidence.coverageBins,
      partial:row.partial,
      deadlineExceeded:row.deadlineExceeded,sourceErrors:row.sourceErrors,
    }));
    return row;
  }catch(error){
    const name=knownFailureNames.has(error?.name)?error.name:"Error";
    const row={id:q.id,group:q.group,language:q.language,status:"REQUEST_FAILED",
      reason:name,phase,elapsedMs:Date.now()-started,
      offers:0,primaryGroups:null,sourceErrors:null,sourceErrorBreakdown:null,
      partial:null,deadlineExceeded:null};
    console.log("R04_P36_CANDIDATE_QUERY "+JSON.stringify(row));
    return row;
  }
}
try{
  await ready();
  let next=0;
  await Promise.all(Array.from({length:2},async()=>{
    while(next<36){const i=next++;rows[i]=await probe(corpus.queryCases[i]);}
  }));
}catch(error){fatal=knownFailureNames.has(error?.name)?error.name:"CANDIDATE_RUN_FAILED";}
finally{
  if(child.exitCode===null){child.kill("SIGTERM");await Promise.race([
    once(child,"close").catch(()=>{}),
    new Promise(r=>setTimeout(r,2000)),
  ]);}
}
const observed=rows.filter(x=>x?.status==="OBSERVED");
const summary={
  attempted:rows.filter(Boolean).length,observed:observed.length,
  requestFailures:rows.filter(x=>x?.status==="REQUEST_FAILED").map(x=>x.id),
  partial:observed.filter(x=>x.partial).length,
  deadlineExceeded:observed.filter(x=>x.deadlineExceeded).length,
  sourceErrorEvents:observed.reduce((n,x)=>n+x.sourceErrors,0),
  observedOffers:observed.reduce((n,x)=>n+x.offers,0),
  intentsWithoutPrincipal:observed.filter(x=>x.primaryGroups===0).map(x=>x.id),
  livePolicyCooldownSkips:observed.reduce((n,x)=>n+(x.localCooldownSkips||0),0),
  actualUpstreamDenialErrors:observed.reduce((n,x)=>n+(x.observedUpstreamDenials||0),0),
  failureAttribution:mergeSourceErrorEvidence(observed.map(x=>x.sourceErrorBreakdown)),
  result:!fatal&&observed.length===36
    ?"CANDIDATE_EVIDENCE_COLLECTED_NOT_CERTIFIED":"CANDIDATE_COLLECTION_FAILED",
};
const releaseGaps=[
  ...(summary.requestFailures.length?["REQUEST_FAILURES"]:[]),
  ...(summary.deadlineExceeded?["INTERNAL_SEARCH_DEADLINES"]:[]),
  ...(summary.intentsWithoutPrincipal.length?["MISSING_PRINCIPAL_GROUPS"]:[]),
];
summary.releaseGatePassed=releaseGaps.length===0;
summary.releaseGaps=releaseGaps;
const criticalPathDiagnostics=TRACE_ENABLED?correlateLiveSearchTraces({
  rows:rows.filter(Boolean),httpSpans:httpTraceEvents,
  generations:criticalPathEvents,expectedIntents:36,
}):null;
if(criticalPathDiagnostics){
  summary.traceAssociation=criticalPathDiagnostics.association;
  summary.traceDropped=traceDropped;
  summary.traceLinkedGenerations=criticalPathDiagnostics.association.GENERATION_OWNER_OBSERVED||0;
  console.log("R04_P46_CORRELATED_SUMMARY "+JSON.stringify({
    sha:SHA,association:summary.traceAssociation,
    httpEvents:httpTraceEvents.length,generationEvents:criticalPathEvents.length,
    truncatedOrInvalidEvents:traceDropped,
    observedCriticalPath:criticalPathDiagnostics.measured,
  }));
}
const report={schemaVersion:"nawaa.r04.p36.disposable-candidate.v1",
  mode:"DISPOSABLE_CANDIDATE_ONLY",sha:SHA,startedAt,
  completedAt:new Date().toISOString(),source:"frozen-36-intent-corpus",
  databaseConfigured:false,meilisearchConfigured:false,
  runMode:"REAL_PUBLIC_MERCHANT_REQUESTS_NO_FIXTURES",
  notEvidenceOf:["currently deployed production code","same-environment causal A/B",
    "every merchant is accessible","human relevance certification","global p95 latency"],
  fatal,summary,rows,criticalPathDiagnostics};
writeFileSync("r04-p36-candidate-36-evidence.json",JSON.stringify(report,null,2)+"\n");
console.log("R04_P36_CANDIDATE_SUMMARY "+JSON.stringify({sha:SHA,...summary}));
// Collection success is not release approval. A real 200 with unrelated
// products or an internal deadline is not a passing customer acceptance.
if(summary.result!=="CANDIDATE_EVIDENCE_COLLECTED_NOT_CERTIFIED")process.exitCode=1;
else if(!summary.releaseGatePassed)process.exitCode=2;
// Diagnostic collection never substitutes for strict merchant relevance; it may
// additionally fail an otherwise green run if no request/generation link exists.
if(TRACE_ENABLED && observed.length>0 &&
  !(criticalPathDiagnostics?.association.GENERATION_OWNER_OBSERVED>0))
  process.exitCode=3;
